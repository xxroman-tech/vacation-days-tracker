BEGIN;
SET LOCAL ROLE vacation_app;

CREATE TABLE public.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar
);

CREATE TABLE public.holiday_types (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar,
    validity integer
);

CREATE TABLE public.user_holiday_budgets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.users (id),
    holiday_type_id integer NOT NULL REFERENCES public.holiday_types (id),
    year integer NOT NULL,
    allowance_minutes decimal(10, 2) NOT NULL CHECK (allowance_minutes >= 0),
    expires_on date NOT NULL,
    created_at date,
    updated_at date,
    UNIQUE (user_id, holiday_type_id, year)
);

CREATE TABLE public.user_holidays (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_id integer NOT NULL REFERENCES public.user_holiday_budgets (id),
    date date NOT NULL,
    hours_used double precision NOT NULL,
    description text,
    created_at date,
    updated_at date,
    UNIQUE (budget_id, date)
);

